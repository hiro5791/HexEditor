/// <summary>
/// 自動化 API の型定義と API リファレンスを、C# の SDK (HexEditor.Sdk) のインターフェイスと XML ドキュメントコメントから作る (AUTO-04 の仕様 2)。
/// <list type="bullet">
/// <item><c>hexeditor.d.ts</c> (英語の説明) と <c>hexeditor.ja.d.ts</c> (日本語の説明): スクリプトエディタの補完・エラー検出 (AUTO-20)。</item>
/// <item><c>jsonrpc-methods.json</c>: 外部からの自動操作 (AUTO-45) のメソッド一覧。</item>
/// <item><c>reference.en.md</c> / <c>reference.ja.md</c>: API リファレンス。</item>
/// </list>
/// 名前は JavaScript の実行環境 (<see cref="JsBinder"/>) と同じ規則で付けるので、型定義と実際の API は食い違わない。
/// </summary>
public sealed class ApiDocGenerator
{
    /// <summary>グローバル変数 (AUTO-03 の仕様 2 と同じ名前)。</summary>
    public static IReadOnlyList<(string Name, Type Type, bool Nullable)> Globals { get; } =
    [
        ("app", typeof(IApp), false),
        ("doc", typeof(IDocument), true),
        ("ui", typeof(IUi), false),
        ("hash", typeof(IHash), false),
        ("clipboard", typeof(IClipboard), false),
        ("settings", typeof(ISettings), false),
        ("script", typeof(IScript), false),
        ("inspector", typeof(IInspector), false),
        ("text", typeof(IText), false),
        ("templates", typeof(ITemplates), false),
        ("fs", typeof(IFileSystem), false),
        ("net", typeof(INet), false),
        ("process", typeof(IProcessRunner), false),
    ];

    private readonly Dictionary<string, XElement> _docs;

    public ApiDocGenerator(string? xmlPath = null)
    {
        xmlPath ??= Path.ChangeExtension(typeof(IApp).Assembly.Location, ".xml");
        _docs = File.Exists(xmlPath)
            ? XDocument.Load(xmlPath).Descendants("member").Where(m => m.Attribute("name") is not null)
                .GroupBy(m => m.Attribute("name")!.Value).ToDictionary(g => g.Key, g => g.First(), StringComparer.Ordinal)
            : [];
    }

    /// <summary>XML ドキュメントコメントを読めたか。</summary>
    public bool HasDocs => _docs.Count > 0;

    /// <summary>API の型 (SDK の公開の型のうち、スクリプトに見せるもの。Hosting 名前空間と属性は除く)。</summary>
    public static IReadOnlyList<Type> ApiTypes { get; } =
        [.. typeof(IApp).Assembly.GetExportedTypes()
            .Where(t => t.Namespace == typeof(IApp).Namespace && !typeof(Attribute).IsAssignableFrom(t) && !typeof(Exception).IsAssignableFrom(t)
                && t != typeof(ScriptGlobals) && t != typeof(ApiInfo))
            .OrderBy(t => SortKey(t)).ThenBy(t => t.Name, StringComparer.Ordinal)];

    private static int SortKey(Type t) => t.IsInterface ? 0 : t.IsAbstract ? 1 : t.IsValueType ? 3 : 2;

    /// <summary>API の例外の型 (AUTO-04 の仕様 9)。</summary>
    public static IReadOnlyList<Type> ErrorTypes { get; } =
        [.. typeof(IApp).Assembly.GetExportedTypes().Where(t => typeof(ScriptError).IsAssignableFrom(t) && !t.IsAbstract).OrderBy(t => t.Name, StringComparer.Ordinal)];

    // ======================== メンバー ========================

    /// <summary>JavaScript から見えるメンバー (<see cref="JsBinder"/> と同じ規則)。</summary>
    public static IReadOnlyList<MemberInfo> MembersOf(Type t)
    {
        var shape = JsBinder.TypeShape.Build(t);
        return [.. shape.Properties.Cast<MemberInfo>().Concat(shape.Methods)];
    }

    /// <summary>メソッドの引数が省略できるか。</summary>
    public static bool IsOptional(ParameterInfo p) =>
        p.HasDefaultValue || Nullable.GetUnderlyingType(p.ParameterType) is not null
        || (!p.ParameterType.IsValueType && new NullabilityInfoContext().Create(p).WriteState == NullabilityState.Nullable);

    // ======================== TypeScript ========================

    public string TypeScript(bool japanese)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine(japanese
            ? "// HexEditor の自動化 API の型定義 (AUTO-04)。HexEditor.Sdk から生成する。手で編集しない。"
            : "// HexEditor automation API type definitions (AUTO-04). Generated from HexEditor.Sdk. Do not edit by hand.");
        sb.AppendLine("// API " + ApiInfo.Version);
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine(japanese
            ? "// 型は名前空間 HexEditor に置く (lib.dom の Document などと混ざらないため)。AbortSignal・console は ECMAScript / DOM の lib を使う。"
            : "// Types live in the namespace HexEditor (so they do not merge with lib.dom's Document etc.). AbortSignal and console come from the ES / DOM libs.");
        sb.AppendLine();
        sb.AppendLine("declare namespace HexEditor {");
        var inner = new StringBuilder();
        foreach (Type t in ApiTypes)
        {
            WriteTsType(inner, t, japanese);
            inner.AppendLine();
        }

        foreach (string line in inner.ToString().TrimEnd().Split('\n'))
        {
            // 空行に空白を残さない (改行が CRLF のときの "\r" だけの行も空行として扱う)
            string trimmed = line.TrimEnd('\r');
            sb.AppendLine(trimmed.Length == 0 ? "" : "    " + trimmed);
        }

        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine("interface AbortSignal { readonly aborted: boolean; readonly reason: unknown; throwIfAborted(): void; }");
        sb.AppendLine();

        foreach (Type e in ErrorTypes)
        {
            WriteDoc(sb, Doc(XmlId(e), japanese), "");
            string extra = e == typeof(PermissionError) ? " readonly permission: string;"
                : e == typeof(LimitError) ? " readonly limit: string;"
                : e == typeof(IoError) ? " readonly offset?: number;" : "";
            if (e == typeof(Sdk.RangeError))
            {
                sb.AppendLine("// RangeError is the ECMAScript built-in RangeError.");
                sb.AppendLine();
                continue;
            }

            sb.AppendLine($"declare class {e.Name} extends Error {{{extra} }}");
            sb.AppendLine();
        }

        foreach ((string name, Type type, bool nullable) in Globals)
        {
            WriteDoc(sb, Doc(XmlId(type), japanese), "");
            sb.AppendLine($"declare const {name}: HexEditor.{JsBinder.TsName(type)}{(nullable ? " | null" : "")};");
        }

        return sb.ToString().Replace("\r\n", "\n", StringComparison.Ordinal);
    }

    private void WriteTsType(StringBuilder sb, Type t, bool ja)
    {
        WriteDoc(sb, Doc(XmlId(t), ja), "");
        string name = JsBinder.TsName(t);
        if (t.IsValueType && t.GetCustomAttribute<TsTypeAttribute>() is { } alias)
        {
            sb.AppendLine($"type {name} = {alias.Type};");
            return;
        }

        bool input = IsInput(t);
        Type? list = ListItem(t);
        string extends = list is not null ? $" extends Iterable<{TsOf(list, null)}>" : "";
        sb.AppendLine($"interface {name}{extends} {{");
        if (list is not null)
        {
            sb.AppendLine("    readonly length: number;");
            sb.AppendLine($"    at(index: number): {TsOf(list, null)} | undefined;");
            sb.AppendLine($"    toArray(): {TsOf(list, null)}[];");
        }

        if (t == typeof(SearchResults))
        {
            sb.AppendLine("    readonly truncated: boolean;");
            sb.AppendLine("    readonly length: number;");
            sb.AppendLine("    [index: number]: ByteRange;");
            sb.AppendLine("}");
            return;
        }

        foreach (MemberInfo m in t.IsInterface || t.IsAbstract ? MembersOf(t) : DataProperties(t))
        {
            WriteDoc(sb, MemberDoc(m, ja), "    ");
            sb.AppendLine("    " + TsMember(m, input) + ";");
        }

        sb.AppendLine("}");
    }

    /// <summary>入力の型 (引数のオプション): 引数なしのコンストラクタがある。すべての欄が省略できる。</summary>
    private static bool IsInput(Type t) => !t.IsInterface && !t.IsAbstract && !t.IsValueType && t.GetConstructor(Type.EmptyTypes) is not null;

    private static Type? ListItem(Type t) =>
        t.IsInterface ? t.GetInterfaces().FirstOrDefault(i => i.IsGenericType && i.GetGenericTypeDefinition() == typeof(IReadOnlyList<>))?.GetGenericArguments()[0] : null;

    private static IEnumerable<MemberInfo> DataProperties(Type t) =>
        t.GetProperties(BindingFlags.Public | BindingFlags.Instance)
            .Where(p => p.GetIndexParameters().Length == 0 && p.Name != "EqualityContract" && p.DeclaringType != typeof(object));

    private static string TsMember(MemberInfo m, bool input)
    {
        if (m is PropertyInfo p)
        {
            bool settable = p.CanWrite && p.SetMethod is { IsPublic: true } set && !IsInitOnly(set);
            string readonlyMark = input || settable ? "" : "readonly ";
            string optional = input ? "?" : "";
            return $"{readonlyMark}{JsBinder.JsName(p)}{optional}: {TsOf(p.PropertyType, p, nullable: IsNullable(p))}";
        }

        var method = (MethodInfo)m;
        IEnumerable<string> ps = method.GetParameters().Select(x => $"{x.Name}{(IsOptional(x) ? "?" : "")}: {TsOf(x.ParameterType, x, nullable: false)}");
        return $"{JsBinder.JsName(method)}({string.Join(", ", ps)}): {TsReturn(method)}";
    }

    private static bool IsInitOnly(MethodInfo setter) =>
        setter.ReturnParameter.GetRequiredCustomModifiers().Any(m => m.FullName == "System.Runtime.CompilerServices.IsExternalInit");

    private static bool IsNullable(PropertyInfo p) =>
        Nullable.GetUnderlyingType(p.PropertyType) is not null
        || (!p.PropertyType.IsValueType && new NullabilityInfoContext().Create(p).ReadState == NullabilityState.Nullable);

    private static string TsReturn(MethodInfo m)
    {
        if (m.GetCustomAttribute<TsTypeAttribute>() is { } attr)
        {
            return attr.Type;
        }

        bool nullable = new NullabilityInfoContext().Create(m.ReturnParameter).ReadState == NullabilityState.Nullable;
        return TsOf(m.ReturnType, null, nullable);
    }

    /// <summary>C# の型を TypeScript の型にする (<see cref="JsBinder"/> の変換と同じ対応)。</summary>
    public static string TsOf(Type t, ICustomAttributeProvider? provider, bool nullable = false)
    {
        if (provider?.GetCustomAttributes(typeof(TsTypeAttribute), false).OfType<TsTypeAttribute>().FirstOrDefault() is { } attr)
        {
            return attr.Type + (nullable ? " | null" : "");
        }

        if (Nullable.GetUnderlyingType(t) is Type inner)
        {
            return TsOf(inner, null) + " | null";
        }

        string ts = t switch
        {
            _ when t == typeof(void) => "void",
            _ when t == typeof(string) => "string",
            _ when t == typeof(bool) => "boolean",
            _ when t == typeof(int) || t == typeof(long) || t == typeof(double) || t == typeof(float) || t == typeof(ulong) => "number",
            _ when t == typeof(BigInteger) => "bigint",
            _ when t == typeof(byte[]) => "Uint8Array",
            _ when t == typeof(long[]) || t == typeof(double[]) => "number[]",
            _ when t == typeof(object) || typeof(JsonNode).IsAssignableFrom(t) => "unknown",
            _ when t == typeof(CancellationToken) => "AbortSignal",
            _ when t == typeof(Task) => "Promise<void>",
            _ when t.IsGenericType && t.GetGenericTypeDefinition() == typeof(Task<>) => $"Promise<{TsOf(t.GetGenericArguments()[0], null)}>",
            _ when t.IsGenericType && t.GetGenericTypeDefinition() == typeof(IAsyncEnumerable<>) => $"AsyncIterable<{TsOf(t.GetGenericArguments()[0], null)}>",
            _ when t.IsGenericType && t.GetGenericTypeDefinition() is var d && (d == typeof(IReadOnlyDictionary<,>) || d == typeof(IDictionary<,>))
                => $"Record<string, {TsOf(t.GetGenericArguments()[1], null)}>",
            _ when t.Namespace == typeof(IApp).Namespace => JsBinder.TsName(t),
            _ when t.IsGenericType && (t.GetGenericTypeDefinition() == typeof(IReadOnlyList<>) || t.GetGenericTypeDefinition() == typeof(IEnumerable<>)
                || t.GetGenericTypeDefinition() == typeof(IReadOnlyCollection<>)) => ArrayOf(TsOf(t.GetGenericArguments()[0], null)),
            _ when typeof(Delegate).IsAssignableFrom(t) => "Function",
            _ => throw new InvalidOperationException($"TypeScript の型に対応がありません: {t}"),
        };
        return ts + (nullable && !t.IsValueType && !ts.EndsWith(" | null", StringComparison.Ordinal) ? " | null" : "");
    }

    private static string ArrayOf(string item) => item.Contains(' ', StringComparison.Ordinal) ? $"({item})[]" : item + "[]";

    // ======================== XML ドキュメントコメント ========================

    private static string XmlId(Type t) => "T:" + t.FullName;

    private string? MemberDoc(MemberInfo m, bool ja)
    {
        string prefix = m is MethodInfo ? "M:" : "P:";
        string id = prefix + m.DeclaringType!.FullName + "." + m.Name;
        XElement? element = m is MethodInfo
            ? _docs.Where(p => p.Key.StartsWith(id + "(", StringComparison.Ordinal) || p.Key == id).Select(p => p.Value).FirstOrDefault()
            : _docs.GetValueOrDefault(id);
        if (element is not null)
        {
            return Text(element.Element("summary"), ja);
        }

        // 位置指定の record の引数の説明 (<param>)。
        if (m is PropertyInfo && _docs.GetValueOrDefault(XmlId(m.DeclaringType)) is { } type)
        {
            XElement? param = type.Elements("param").FirstOrDefault(e => e.Attribute("name")?.Value == m.Name);
            return Text(param, ja);
        }

        return null;
    }

    private string? Doc(string id, bool ja) => _docs.GetValueOrDefault(id) is { } e ? Text(e.Element("summary"), ja) : null;

    /// <summary>説明の文字列 (<c>&lt;ja&gt;</c> は日本語、それ以外は英語。<c>&lt;c&gt;</c> は <c>`...`</c>)。</summary>
    private static string? Text(XElement? element, bool ja)
    {
        if (element is null)
        {
            return null;
        }

        XElement? source = ja ? element.Element("ja") ?? element : element;
        var sb = new StringBuilder();
        foreach (XNode node in source.Nodes())
        {
            Append(sb, node, skipJa: true);
        }

        string text = string.Join(" ", sb.ToString().Split((char[])['\r', '\n'], StringSplitOptions.RemoveEmptyEntries).Select(l => l.Trim())).Trim();
        return text.Length == 0 ? null : text;
    }

    private static void Append(StringBuilder sb, XNode node, bool skipJa)
    {
        switch (node)
        {
            case XText text:
                sb.Append(text.Value);
                break;
            case XElement { Name.LocalName: "ja" } when skipJa:
                break;
            case XElement { Name.LocalName: "c" } c:
                sb.Append('`').Append(c.Value).Append('`');
                break;
            case XElement { Name.LocalName: "see" } see:
                string cref = see.Attribute("cref")?.Value ?? see.Attribute("langword")?.Value ?? "";
                int paren0 = cref.IndexOf('(', StringComparison.Ordinal);
                string bare = paren0 > 0 ? cref[..paren0] : cref;
                string shortName = bare[(bare.LastIndexOf('.') + 1)..];
                if (cref.StartsWith("M:", StringComparison.Ordinal) || cref.StartsWith("P:", StringComparison.Ordinal))
                {
                    // メンバーは JavaScript の名前で書く。
                    if (cref.StartsWith("M:", StringComparison.Ordinal) && shortName.EndsWith("Async", StringComparison.Ordinal) && shortName.Length > 5)
                    {
                        shortName = shortName[..^5];
                    }

                    shortName = JsBinder.CamelCase(shortName);
                }
                else if (cref.StartsWith("T:", StringComparison.Ordinal) && shortName.Length > 1 && shortName[0] == 'I' && char.IsUpper(shortName[1]))
                {
                    shortName = shortName[1..];
                }

                sb.Append('`').Append(shortName).Append('`');
                break;
            case XElement { Name.LocalName: "paramref" } pr:
                sb.Append('`').Append(pr.Attribute("name")?.Value).Append('`');
                break;
            case XElement e:
                foreach (XNode child in e.Nodes())
                {
                    Append(sb, child, skipJa);
                }

                break;
        }
    }

    private static void WriteDoc(StringBuilder sb, string? text, string indent)
    {
        if (!string.IsNullOrEmpty(text))
        {
            sb.Append(indent).Append("/** ").Append(text.Replace("*/", "* /", StringComparison.Ordinal)).AppendLine(" */");
        }
    }

