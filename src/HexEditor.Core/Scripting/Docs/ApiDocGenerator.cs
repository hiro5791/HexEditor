    /// <summary>API リファレンス (Markdown)。型ごとに「## 型」、メンバーごとに「### 型.メンバー」の見出しを付ける。</summary>
    public string Reference(bool ja)
    {
        var sb = new StringBuilder();
        sb.AppendLine(ja ? "# 自動化 API リファレンス" : "# Automation API reference");
        sb.AppendLine();
        sb.AppendLine(ja
            ? $"API バージョン {ApiInfo.Version}。HexEditor.Sdk から生成する (手で編集しない)。JavaScript の名前を示す (C# では先頭を大文字にし、非同期のメソッドには `Async` が付く)。"
            : $"API version {ApiInfo.Version}. Generated from HexEditor.Sdk (do not edit by hand). Names are the JavaScript names (C# uses PascalCase and the `Async` suffix for asynchronous methods).");
        sb.AppendLine();
        sb.AppendLine(ja ? "## グローバル変数" : "## Globals");
        sb.AppendLine();
        foreach ((string name, Type type, bool nullable) in Globals)
        {
            sb.AppendLine($"- `{name}`: `{JsBinder.TsName(type)}{(nullable ? " | null" : "")}`");
        }

        sb.AppendLine();
        foreach (Type t in ApiTypes)
        {
            string name = JsBinder.TsName(t);
            sb.AppendLine($"## {name}");
            sb.AppendLine();
            if (Doc(XmlId(t), ja) is { } summary)
            {
                sb.AppendLine(summary);
                sb.AppendLine();
            }

            if (t.IsValueType && t.GetCustomAttribute<TsTypeAttribute>() is { } alias)
            {
                sb.AppendLine($"`type {name} = {alias.Type}`");
                sb.AppendLine();
                continue;
            }

            bool input = IsInput(t);
            foreach (MemberInfo m in t.IsInterface || t.IsAbstract ? MembersOf(t) : DataProperties(t))
            {
                sb.AppendLine($"### {name}.{JsBinder.JsName(m)}");
                sb.AppendLine();
                sb.AppendLine($"`{TsMember(m, input)}`");
                sb.AppendLine();
                if (MemberDoc(m, ja) is { } text)
                {
                    sb.AppendLine(text);
                    sb.AppendLine();
                }

                if (m.GetCustomAttribute<RequiresPermissionAttribute>() is { } perm)
                {
                    sb.AppendLine(ja ? $"許可: `{perm.Permission}`" : $"Permission: `{perm.Permission}`");
                    sb.AppendLine();
                }
            }
        }

        sb.AppendLine(ja ? "## 例外" : "## Errors");
        sb.AppendLine();
        foreach (Type e in ErrorTypes)
        {
            sb.AppendLine($"- `{e.Name}`: {Doc(XmlId(e), ja)}");
        }

        return sb.ToString().Replace("\r\n", "\n", StringComparison.Ordinal);
    }

    /// <summary>生成する成果物 (ファイル名と内容)。</summary>
    public IReadOnlyList<(string FileName, string Content)> Artifacts() =>
    [
        ("hexeditor.d.ts", TypeScript(japanese: false)),
        ("hexeditor.ja.d.ts", TypeScript(japanese: true)),
        ("jsonrpc-methods.json", JsonRpcMethods()),
        ("reference.en.md", Reference(ja: false)),
        ("reference.ja.md", Reference(ja: true)),
    ];

    internal static string Invariant(FormattableString s) => s.ToString(CultureInfo.InvariantCulture);
